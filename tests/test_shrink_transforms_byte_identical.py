def _load(src: str, name: str):
    code = base64.b64decode(src.encode()).decode()
    spec = importlib.util.spec_from_loader(name, loader=None)
    mod = importlib.util.module_from_spec(spec)
    exec(compile(code, name + ".py", "exec"), mod.__dict__)
    return mod


_orig_ue = _load(_ORIG_USE_ENUMERATE_B64, "_orig_use_enumerate")
_orig_nw = _load(_ORIG_NESTED_WITH_B64, "_orig_nested_with")


def _write(tmp_path, source: str, rel: str = "app/m.py"):
    (tmp_path / "app").mkdir(exist_ok=True)
    path = tmp_path / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(source), encoding="utf-8")
    return path


def _plan_tuple(plan):
    return (
        dict(plan.new_contents),
        sorted(plan.blockers),
        dict(plan.edits_by_file),
    )


def _check(tmp_path, source, orig_plan_fn, live_plan_fn, rel="app/m.py"):
    _write(tmp_path, source, rel)
    orig = orig_plan_fn(str(tmp_path), rel)
    live = live_plan_fn(str(tmp_path), rel)
    assert _plan_tuple(orig) == _plan_tuple(live), source


