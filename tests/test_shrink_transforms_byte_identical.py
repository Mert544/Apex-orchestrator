_USE_ENUMERATE_CORPUS = [
    # canonical convert
    "def f(xs):\n    t = 0\n    for i in range(len(xs)):\n        t += xs[i]\n    return t\n",
    # attribute-chain seq
    "def f(self):\n    for i in range(len(self.items)):\n        print(self.items[i])\n",
    # multi-use of seq[i]
    "def f(xs):\n    for i in range(len(xs)):\n        a = xs[i]\n        b = xs[i] + 1\n        print(a, b)\n",
    # nested loops (only outer or inner convertible / overlap handling)
    "def f(xs, ys):\n    for i in range(len(xs)):\n        for i in range(len(ys)):\n            print(xs[i], ys[i])\n",
    # top-level loop (module scope)
    "xs = [1, 2, 3]\nfor i in range(len(xs)):\n    print(xs[i])\n",
    # collision: xs_item already used
    "def f(xs):\n    xs_item = 0\n    for i in range(len(xs)):\n        print(xs[i], xs_item)\n",
    # ---- must NOT convert ----
    # for/else
    "def f(xs):\n    for i in range(len(xs)):\n        print(xs[i])\n    else:\n        pass\n",
    # i used elsewhere
    "def f(xs):\n    for i in range(len(xs)):\n        print(i, xs[i])\n",
    # store seq[i] = ...
    "def f(xs):\n    for i in range(len(xs)):\n        xs[i] = 0\n",
    # start-stop range
    "def f(xs):\n    for i in range(0, len(xs)):\n        print(xs[i])\n",
    # range(len(a), len(b))
    "def f(a, b):\n    for i in range(len(a), len(b)):\n        print(a[i])\n",
    # seq rebound in body
    "def f(xs):\n    for i in range(len(xs)):\n        xs = []\n        print(xs[i])\n",
    # i captured by nested function
    "def f(xs):\n    for i in range(len(xs)):\n        g = lambda: i\n        print(xs[i], g)\n",
    # no seq[i] usage at all
    "def f(xs):\n    for i in range(len(xs)):\n        print('x')\n",
    # target not i
    "def f(xs):\n    for j in range(len(xs)):\n        print(xs[j])\n",
    # range with keyword
    "def f(xs):\n    for i in range(len(xs), step=1):\n        print(xs[i])\n",
    # len of a call (not name/attr chain)
    "def f():\n    for i in range(len(get())):\n        print(get()[i])\n",
    # subscript by something other than i
    "def f(xs):\n    j = 0\n    for i in range(len(xs)):\n        print(xs[j])\n",
    # empty-ish / no match
    "def f():\n    return 1\n",
    # different seq indexed (xs[i] but iter over len(ys))
    "def f(xs, ys):\n    for i in range(len(ys)):\n        print(xs[i])\n",
    # async-equivalent: not a For (just ensure no crash) handled via async def body
    "async def f(xs):\n    for i in range(len(xs)):\n        print(xs[i])\n",
]


